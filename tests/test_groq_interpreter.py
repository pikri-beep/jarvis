"""Unit tests for Groq-powered Action Interpreter and Unified Conversational Responder."""

import unittest
from unittest.mock import MagicMock, patch

from app.ai.interpreter import ActionInterpreter, InterpreterPlan
from app.core.config import Settings
from app.core.orchestrator import Orchestrator
from app.core.router import RouteResult, RouteType


class TestGroqActionInterpreter(unittest.TestCase):
    def setUp(self):
        self.settings = Settings(
            interpreter_provider="groq",
            groq_model="qwen/qwen3.8-27b",
            groq_api_key="mock_key",
        )

    @patch("groq.Groq")
    def test_initialization_with_groq_provider(self, mock_groq_class):
        """Verify ActionInterpreter initializes Groq client when provider is groq."""
        interpreter = ActionInterpreter(settings=self.settings)
        mock_groq_class.assert_called_once_with(api_key="mock_key")
        self.assertEqual(interpreter.provider, "groq")
        self.assertEqual(interpreter.groq_model, "qwen/qwen3.8-27b")
        self.assertTrue(interpreter.is_available())

    def test_groq_interprets_action_plan(self):
        """Verify parsing and validation of action JSON generated by Groq."""
        interpreter = ActionInterpreter(settings=self.settings)
        mock_client = MagicMock()
        mock_resp = MagicMock()
        mock_resp.choices = [
            MagicMock(
                message=MagicMock(
                    content='{"type": "action", "intent": "web_search", "action": "search_web", "target": "web", "parameters": {"query": "resep soto ayam"}}'
                )
            )
        ]
        mock_client.chat.completions.create.return_value = mock_resp
        interpreter._groq_client = mock_client

        plan = interpreter.interpret("tolong cariin resep soto ayam dong", language="id")

        self.assertTrue(plan.is_action)
        self.assertEqual(plan.intent, "web_search")
        self.assertIn(plan.action, ("search", "search_web"))
        self.assertEqual(plan.parameters.get("query"), "resep soto ayam")

    def test_groq_interprets_conversational_chat(self):
        """Verify conversational Q&A plan returns direct response text."""
        interpreter = ActionInterpreter(settings=self.settings)
        mock_client = MagicMock()
        mock_resp = MagicMock()
        mock_resp.choices = [
            MagicMock(
                message=MagicMock(
                    content='{"type": "conversation", "intent": "system", "action": "", "target": "", "response": "Presiden pertama Indonesia adalah Soekarno, sir."}'
                )
            )
        ]
        mock_client.chat.completions.create.return_value = mock_resp
        interpreter._groq_client = mock_client

        plan = interpreter.interpret("siapa presiden pertama indonesia?", language="id")

        self.assertEqual(plan.type, "conversation")
        self.assertEqual(plan.response, "Presiden pertama Indonesia adalah Soekarno, sir.")

    def test_groq_error_falls_back_gracefully(self):
        """Verify network/API error on Groq gracefully falls back to Ollama."""
        interpreter = ActionInterpreter(settings=self.settings)
        mock_client = MagicMock()
        mock_client.chat.completions.create.side_effect = RuntimeError("Groq Connection Refused")
        interpreter._groq_client = mock_client

        with patch.object(interpreter, "_interpret_ollama") as mock_ollama:
            mock_ollama.return_value = InterpreterPlan(
                type="conversation",
                response="Fallback response",
            )
            plan = interpreter.interpret("hello world")
            mock_ollama.assert_called_once()
            self.assertEqual(plan.response, "Fallback response")

    def test_ai_handler_with_groq_interpreter(self):
        """Verify Orchestrator AI handler outputs conversational response from Groq directly."""
        orchestrator = Orchestrator(settings=self.settings)
        mock_plan = InterpreterPlan(
            type="conversation",
            response="Ini adalah jawaban langsung dari Groq, sir.",
        )
        orchestrator.interpreter.interpret = MagicMock(return_value=mock_plan)

        route = RouteResult(route_type=RouteType.AI_REQUEST, raw_input="tes pertanyaan")
        from app.core.handlers.ai_handler import handle_ai_request

        res_route, stream_gen = handle_ai_request(orchestrator, route, "tes pertanyaan", "id", True)
        tokens = list(stream_gen)
        output_text = "".join(tokens)

        self.assertIn("jawaban langsung dari Groq", output_text)


if __name__ == "__main__":
    unittest.main()
