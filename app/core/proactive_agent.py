"""Proactive Initiative System for JARVIS on Windows 11.

Monitors light desktop context (time, active window, and persistent memory facts)
to proactively provide context-aware suggestions, greetings, and assistance without
interrupting ongoing speech or user commands.
"""

from dataclasses import dataclass, field
import datetime
import logging
import re
import time
from typing import Any, Dict, Optional

from app.core.config import Settings, get_settings
from app.core.logger import setup_logger

logger = setup_logger("jarvis.core.proactive")


@dataclass
class ProactiveEvent:
    """Represents a proactive intervention or suggestion generated by JARVIS."""
    display_message: str
    spoken_message: str
    category: str  # "startup_greeting", "app_assistance", "focus_break", "error_assistance", "time_check"
    timestamp: float = field(default_factory=time.time)
    suggested_prompt: Optional[str] = None


class ProactiveAgent:
    """Evaluates background context to initiate helpful, proactive interactions."""

    def __init__(self, settings: Optional[Settings] = None, orchestrator: Optional[Any] = None):
        self.settings = settings or get_settings()
        self.orchestrator = orchestrator
        self.last_event_time: float = 0.0
        self.cooldown_seconds: float = getattr(self.settings, "proactive_cooldown_seconds", 60.0)
        self.check_interval_seconds: float = getattr(self.settings, "proactive_interval_seconds", 900.0)
        self.startup_greeted: bool = False
        self.last_active_window: str = ""
        self.active_window_start_time: float = time.time()
        self.last_focus_break_time: float = 0.0

    def is_enabled(self) -> bool:
        """Checks if proactive features are enabled in settings."""
        return getattr(self.settings, "proactive_enabled", True)

    def is_voice_idle(self) -> bool:
        """Verifies that voice and user interaction state is strictly IDLE."""
        if not self.orchestrator:
            return True

        # 1. Check active user turn processing in state
        if getattr(self.orchestrator.state, "is_processing", False):
            return False

        # 2. Check pending confirmation or clarify dialog
        if getattr(self.orchestrator.state, "pending_action", None) is not None:
            return False

        # 3. Check WakeWordDetector state
        try:
            wake = self.orchestrator.wake_word
            if wake and hasattr(wake, "is_busy") and callable(wake.is_busy) and wake.is_busy():
                return False
        except Exception:
            pass

        # 4. Check TTS engine active speech
        try:
            tts = self.orchestrator.tts
            if tts and hasattr(tts, "is_speaking") and callable(tts.is_speaking) and tts.is_speaking():
                return False
        except Exception:
            pass

        return True

    def check_context(self, current_time_ts: Optional[float] = None) -> Optional[ProactiveEvent]:
        """Evaluates time, active window, and user memory to determine if a proactive event should fire."""
        if not self.is_enabled():
            return None

        now_ts = current_time_ts or time.time()

        # Voice state check (must be idle to avoid interrupting user)
        if not self.is_voice_idle():
            return None

        # Retrieve user profile & honorific from memory
        from app.memory.memory import memory_manager
        honorific = memory_manager.get_honorific("sir")
        lang = "id"
        if self.orchestrator and hasattr(self.orchestrator.state, "conversation_language"):
            lang = self.orchestrator.state.conversation_language or "id"
        is_id = lang.startswith("id")

        # Context 1: Active Window and Process
        from app.tools.desktop import get_active_window_details
        det = get_active_window_details()
        win_title = det.title.strip() if det.title else ""
        proc_name = det.process_name.lower().replace(".exe", "")

        # Track window duration
        if win_title != self.last_active_window:
            self.last_active_window = win_title
            self.active_window_start_time = now_ts
        win_duration_minutes = (now_ts - self.active_window_start_time) / 60.0

        # Context 2: Current Time and Date
        from app.tools.datetime_tool import get_current_time
        curr_time_str = get_current_time(lang=lang)

        # TRIGGER 1: Window Anomaly / Error Window Detection (Immediate assistance)
        # If active window has an error/crash indication, offer immediate proactive assistance
        if any(w in win_title.lower() for w in ["error", "crash", "not responding", "exception", "failed", "gagal"]):
            self.last_event_time = now_ts
            if is_id:
                disp = f"⚠️ Terdeteksi indikasi kendala pada jendela '{win_title}'. Apakah Anda ingin saya membaca error di layar, {honorific}?"
                spoken = f"Saya melihat ada indikasi kendala pada jendela {win_title}, {honorific}. Apakah Anda ingin saya memeriksa pesan error di layar?"
            else:
                disp = f"⚠️ Issue detected on window '{win_title}'. Would you like me to inspect the error on screen, {honorific}?"
                spoken = f"I noticed an issue in window {win_title}, {honorific}. Would you like me to inspect the error on screen?"

            return ProactiveEvent(
                display_message=disp,
                spoken_message=spoken,
                category="error_assistance",
                suggested_prompt="bacakan error di layar",
                timestamp=now_ts,
            )

        # TRIGGER 2: Due Todo Reminder Check (Scheduled alert)
        try:
            db = None
            if self.orchestrator and hasattr(self.orchestrator, "memory") and hasattr(self.orchestrator.memory, "db"):
                db = self.orchestrator.memory.db
            else:
                from app.memory.database import Database
                db = Database()

            unreminded_todos = db.get_due_unreminded_todos()
            if unreminded_todos:
                now_dt = datetime.datetime.now()
                now_minutes = now_dt.hour * 60 + now_dt.minute

                for todo in unreminded_todos:
                    due_str = (todo.get("due_date") or "").strip()
                    m_due = re.search(r"(\d{1,2})[:\.](\d{2})", due_str)
                    if m_due:
                        due_h = int(m_due.group(1))
                        due_m = int(m_due.group(2))
                        due_minutes = due_h * 60 + due_m

                        # If current time is at or after due time (within same day window, up to 120 mins)
                        if 0 <= (now_minutes - due_minutes) <= 120:
                            db.mark_todo_reminded(todo["id"])
                            self.last_event_time = now_ts
                            t_title = todo.get("title", "Tugas")
                            if is_id:
                                disp = f"⏰ PENGINGAT TUGAS: '{t_title}' sudah waktunya ({due_str}), {honorific}."
                                spoken = f"Permisi {honorific}, ini pengingat untuk tugas Anda: {t_title}."
                            else:
                                disp = f"⏰ TASK REMINDER: '{t_title}' is due ({due_str}), {honorific}."
                                spoken = f"Excuse me {honorific}, this is a reminder for your task: {t_title}."

                            return ProactiveEvent(
                                display_message=disp,
                                spoken_message=spoken,
                                category="todo_reminder",
                                timestamp=now_ts,
                            )
                    elif any(w in due_str.lower() for w in ["hari ini", "sekarang", "today"]):
                        db.mark_todo_reminded(todo["id"])
                        self.last_event_time = now_ts
                        t_title = todo.get("title", "Tugas")
                        if is_id:
                            disp = f"⏰ PENGINGAT TUGAS: '{t_title}', {honorific}."
                            spoken = f"Permisi {honorific}, ini pengingat untuk tugas: {t_title}."
                        else:
                            disp = f"⏰ TASK REMINDER: '{t_title}', {honorific}."
                            spoken = f"Excuse me {honorific}, this is a reminder for: {t_title}."

                        return ProactiveEvent(
                            display_message=disp,
                            spoken_message=spoken,
                            category="todo_reminder",
                            timestamp=now_ts,
                        )
        except Exception as todo_err:
            logger.debug("Error checking due todo reminders: %s", todo_err)

        # Cooldown enforcement for ambient suggestions (Greetings & focus breaks)
        if self.last_event_time > 0 and (now_ts - self.last_event_time) < self.cooldown_seconds:
            return None

        # TRIGGER 2: Startup & Workspace Welcome (first active window detection)
        if not self.startup_greeted and win_title:
            self.startup_greeted = True
            self.last_event_time = now_ts

            preferred_editor = memory_manager.get_preferred_tool("editor", "VS Code")
            if any(ide in proc_name for ide in ["code", "cursor", "devenv", "pycharm", "idea"]):
                if is_id:
                    disp = f"💡 JARVIS aktif. Anda sedang membuka lingkungan kerja '{win_title}'. Siap mendampingi Anda, {honorific}."
                    spoken = f"Selamat beraktivitas, {honorific}. Saya melihat Anda sedang membuka {preferred_editor}. Ada tugas atau kode yang ingin kita lanjutkan?"
                else:
                    disp = f"💡 JARVIS active. Workspace '{win_title}' is ready. Standing by to assist, {honorific}."
                    spoken = f"Good to see you, {honorific}. I see {preferred_editor} is open. Shall we continue your work?"
            else:
                if is_id:
                    disp = f"✨ JARVIS siap mendampingi Anda di Windows 11, {honorific}."
                    spoken = f"Halo {honorific}, saya siap membantu aktivitas Anda di komputer hari ini."
                else:
                    disp = f"✨ JARVIS is standing by to assist on Windows 11, {honorific}."
                    spoken = f"Hello {honorific}, I am ready to assist you today."

            return ProactiveEvent(
                display_message=disp,
                spoken_message=spoken,
                category="startup_greeting",
                suggested_prompt="apa yang bisa kamu bantu?",
                timestamp=now_ts,
            )

        # TRIGGER 3: Continuous Deep Focus Session (> 25 minutes on a single work window)
        if (
            win_duration_minutes >= 25.0
            and (now_ts - self.last_focus_break_time) >= 1500.0  # 25 min break interval
            and any(w in proc_name for w in ["code", "cursor", "chrome", "msedge", "firefox", "word", "excel"])
        ):
            self.last_focus_break_time = now_ts
            self.last_event_time = now_ts
            mins_int = int(win_duration_minutes)
            if is_id:
                disp = f"⏳ Anda telah fokus di '{win_title[:30]}' selama {mins_int} menit, {honorific}. Disarankan istirahat sejenak."
                spoken = f"Anda telah fokus bekerja selama {mins_int} menit, {honorific}. Jangan lupa rehat sejenak dan minum air."
            else:
                disp = f"⏳ You have been focused on '{win_title[:30]}' for {mins_int} minutes, {honorific}. Consider taking a short break."
                spoken = f"You have been working continuously for {mins_int} minutes, {honorific}. Please consider taking a short break."

            return ProactiveEvent(
                display_message=disp,
                spoken_message=spoken,
                category="focus_break",
                timestamp=now_ts,
            )

        return None
